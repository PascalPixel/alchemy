/* Whether the party is in the tent on SoutheastAngaraIslet or the hut on
   WestIndraIslet's pier, which this overlay also holds. */
#define IN_ISLET_ROOMS() \
	(MainRoutineStateWork.next == SCENE_CHAMPA_ROOMS && \
		(MainRoutineStateWork.entrance == \
				CHAMPA_ROOMS_FROM_SOUTHEAST_ANGARA_ISLET || \
			MainRoutineStateWork.entrance == \
				CHAMPA_ROOMS_FROM_WEST_INDRA_ISLET))

/* The islet rooms' one actor, in the hut on WestIndraIslet's pier. */
typedef enum CHAMPA_ISLET_ACTOR_ID {
	ACTOR_INDRA_NEIGHBOR = ACTOR_FIRST_PLACED
} CHAMPA_ISLET_ACTOR_ID;

const SCENE_ENTRANCE *scGetEntrances(void)
{
	return SceneEntrances;
}

const SCENE_REGION *scGetExitRegions(void)
{
	return 0;
}

