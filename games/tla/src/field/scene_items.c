/// A scene's header: its number with bit 14 set, and the flag (-1 for always)
/// whose being set skips these rows (SceneItem_GetRows). A scene number cannot
/// be a symbol in a halfword, so each header names its scene in a comment.
#define SCENE_ITEMS(scene, flag) (0x4000 | (scene)), (flag)

/// A treasure spot: its kind, which picks its sprite in
/// Field_PlaceTreasureSpots (128 and 129 one, 130 another, 131 a third, 132
/// SPRITE_STONE_TABLET; any other kind is buried, with the third's sprite),
/// the scene point it stands on, the flag set once it is taken (-1 for none; a
/// kind-128 spot stays once its flag is set) and what it holds.
#define SCENE_ITEM(kind, point, flag, item) (kind), (point), (flag), (item)

/// What a spot holds when bit 15 is set: a quantity n rather than an item, for
/// which the spot shows no item icon.
#define SCENE_ITEM_QUANTITY(n) (0x8000 + (n))

