    /// Vectors captured from `bun -e 'console.log(Bun.hash(Buffer.from(...)))'`
    /// on Bun 1.3.14. Lengths straddle every branch: empty, sub-4, the 4..=16
    /// small-key path, the 17..48 `final1`-only path, exactly 48, and multi-block.
    #[test]
    fn matches_bun_hash_on_captured_vectors() {
        let cases: &[(&str, u64)] = &[
            ("", 290873116282709081),
            ("a", 2941419223392617777),
            ("abc", 190542993387777138),
            ("hello world", 7389666205914310003),
            ("xxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxxx", 7692055816218192354),
        ];
        for (input, expected) in cases {
            assert_eq!(bun_hash(input.as_bytes()), *expected, "input {input:?}");
        }
        assert_eq!(bun_hash(&b"y".repeat(200)), 7399822228957620249);
    }

    #[test]
    fn base36_matches_bigint_to_string() {
        assert_eq!(base36(290873116282709081), "27k1wwwhf13t");
        assert_eq!(base36(7389666205914310003), "1k55m1pptz88j");
        assert_eq!(base36(0), "0");
        assert_eq!(base36(35), "z");
        assert_eq!(base36(36), "10");
        assert_eq!(base36(u64::MAX), "3w5e11264sgsf");
    }

