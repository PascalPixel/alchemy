// キャラクタ：PP の設定とゲージの計算
//--------------------------------------------------------------------------

#include "battle_unit.h"

//--------------------------------------------------------------------------
// PP を 0 から最大 PP の間で設定し、HP と PP のゲージを計算し直す
// ゲージは 0x4000 で満タン。残っていれば最低 1 にする
// unit : ユニット
// pp   : 新しい PP
//--------------------------------------------------------------------------
void Owner_UpdateSecondInputAndRatios(struct BattleUnit *unit, s32 pp)
{
    s32 cur;

    if (pp > unit->maxPp)
    {
        cur = unit->maxPp;
    }
    else
    {
        cur = 0;
        if (pp >= 0)
            cur = pp;
    }
    unit->pp = cur;
    Unit_UpdateGauges(unit);
}
