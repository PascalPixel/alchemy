//--------------------------------------------------------------------------
// clear_word_if_set.c
// メモリ：0 でないワードを 0 にする
//--------------------------------------------------------------------------

#include "types.h"
#include "scene.h"

//--------------------------------------------------------------------------
// *p が 0 でなければ 0 にして、p を返す
//--------------------------------------------------------------------------
s32 *Runtime_ClearWordIfSet(s32 *p)
{
    if (*p != 0)
    {
        *p = 0;
    }
    return p;
}
