//--------------------------------------------------------------------------
// format_hex.c
// 文字：数を 16 進の文字列にする
//--------------------------------------------------------------------------

#include "types.h"

//--------------------------------------------------------------------------
// value の下から count けた（5 けたまで）を、上のけたから大文字の
// 16 進で out に書く（終わりの 0 は書かない）
//--------------------------------------------------------------------------
void Text_FormatHex(u32 value, u32 count, u8 *out)
{
	u8	buf[8];
	u32 i;

	if (count > 5)
		count = 5;

	for (i = 0; i != count; i++)
	{
		u32 d = value & 15;
		if (d <= 9)
			buf[i] = d + '0';
		else
			buf[i] = d + 'A' - 10;
		value >>= 4;
	}

	for (i = count - 1; (s32)i >= 0; i--)
		*out++ = buf[i];
}
