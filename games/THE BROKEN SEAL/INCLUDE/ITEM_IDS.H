#ifndef ALCHEMY_ITEM_IDS_H
#define ALCHEMY_ITEM_IDS_H

/* Item ids; an item's name is message 0x182 plus its id. */
enum ItemId {
    ITEM_NUT = 0xb5,
    ITEM_VIAL = 0xb6,
    ITEM_ANTIDOTE = 0xbb,
    ITEM_ELIXIR = 0xbc,
    ITEM_WATER_OF_LIFE = 0xbd,
    ITEM_SMOKE_BOMB = 0xe2,
    ITEM_SLEEP_BOMB = 0xe3,
    ITEM_LUCKY_MEDAL = 0xe5,
    ITEM_BLACK_ORB = 0xf2
};

#endif
