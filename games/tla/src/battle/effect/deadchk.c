//--------------------------------------------------------------------------
// deadchk.c
// バトル：倒れた相手にも追加効果を出す効果の判定
//--------------------------------------------------------------------------

#include "types.h"

//--------------------------------------------------------------------------
// 対象が倒れていても追加効果を出す効果なら 1 を返す
// うばう効果は、与えたダメージを行動側に戻すため
// efx : 効果番号
//--------------------------------------------------------------------------
s32 BtlEfxDeadChk(s32 efx)
{
	switch (efx)
	{
	case 31: // HPをうばう
	case 32: // PPをうばう
	case 60: // HPをうばう（半分）
	case 69: // PPをうばう（1/10）
		return 1;
	default:
		return 0;
	}
}
