// キャラクタ：EP の設定とゲージの計算
//--------------------------------------------------------------------------

#include "battle_unit.h"

//--------------------------------------------------------------------------
// EP を 0 から最大 EP の間で設定し、HP と EP のゲージを計算し直す
// ゲージは 0x4000 で満タン。残っていれば最低 1 にする
// unit : ユニット
// ep   : 新しい EP
//--------------------------------------------------------------------------
void Owner_UpdateSecondInputAndRatios(struct BtlUnit *unit, s32 ep)
{
	s32 cur;

	if (ep > unit->max_ep)
	{
		cur = unit->max_ep;
	}
	else
	{
		cur = 0;
		if (ep >= 0)
			cur = ep;
	}
	unit->ep = cur;
	Unit_UpdateGauges(unit);
}
