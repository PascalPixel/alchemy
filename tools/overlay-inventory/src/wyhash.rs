// Bun.hash — the 64-bit wyhash Bun exposes as its default hash.
//
// WHY THIS FILE EXISTS
// The queue caches a diagnosis under `${stem}:${Bun.hash(bytes).toString(36)}`
// and writes that hash into the durable report. If the hash differed from
// Bun's by a single bit, every cache lookup would miss and every `source_hash`
// field in `out/decomp/queue.json` would silently change — a rewrite of a
// tracked artifact disguised as a port. So this is not "a hash"; it is Bun's
// hash, reproduced exactly.
//
// PORT NOTE: `Bun.hash(x)` is `std.hash.Wyhash.hash(0, x)` from Zig's standard
// library (wyhash final version 3). The implementation below is a transcription
// of `lib/zig/std/hash/wyhash.zig`; the one-shot `hash` entry point is all the
// queue needs, so the streaming `update`/`final` half is not ported.
//
// PORT NOTE: `Bun.hash` returns a **bigint**, not a number, so
// `.toString(36)` is an exact 64-bit unsigned base-36 rendering with no
// double-precision truncation. `base36` below matches that, not
// `(value as f64).to_string()`.

const SECRET: [u64; 4] = [
    0xa076_1d64_78bd_642f,
    0xe703_7ed1_a0b4_28db,
    0x8ebc_6af0_9c88_c6e3,
    0x5899_65cc_7537_4cc3,
];

fn mum(a: &mut u64, b: &mut u64) {
    let product = (*a as u128).wrapping_mul(*b as u128);
    *a = product as u64;
    *b = (product >> 64) as u64;
}

fn mix(a: u64, b: u64) -> u64 {
    let (mut a, mut b) = (a, b);
    mum(&mut a, &mut b);
    a ^ b
}

fn read(bytes: usize, data: &[u8]) -> u64 {
    let mut value = 0u64;
    for (index, byte) in data.iter().take(bytes).enumerate() {
        value |= (*byte as u64) << (8 * index);
    }
    value
}

struct State {
    a: u64,
    b: u64,
    state: [u64; 3],
    total_len: usize,
}

impl State {
    fn new(seed: u64) -> State {
        let first = seed ^ mix(seed ^ SECRET[0], SECRET[1]);
        State {
            a: 0,
            b: 0,
            state: [first, first, first],
            total_len: 0,
        }
    }

    fn small_key(&mut self, input: &[u8]) {
        if input.len() >= 4 {
            let end = input.len() - 4;
            let quarter = (input.len() >> 3) << 2;
            self.a = (read(4, input) << 32) | read(4, &input[quarter..]);
            self.b = (read(4, &input[end..]) << 32) | read(4, &input[end - quarter..]);
        } else if !input.is_empty() {
            self.a = ((input[0] as u64) << 16)
                | ((input[input.len() >> 1] as u64) << 8)
                | (input[input.len() - 1] as u64);
            self.b = 0;
        } else {
            self.a = 0;
            self.b = 0;
        }
    }

    fn round(&mut self, input: &[u8]) {
        for index in 0..3 {
            let a = read(8, &input[8 * (2 * index)..]);
            let b = read(8, &input[8 * (2 * index + 1)..]);
            self.state[index] = mix(a ^ SECRET[index + 1], b ^ self.state[index]);
        }
    }

    fn final0(&mut self) {
        self.state[0] ^= self.state[1] ^ self.state[2];
    }

    fn final1(&mut self, input_lb: &[u8], start: usize) {
        let input = &input_lb[start..];
        let mut index = 0usize;
        while index + 16 < input.len() {
            self.state[0] = mix(
                read(8, &input[index..]) ^ SECRET[1],
                read(8, &input[index + 8..]) ^ self.state[0],
            );
            index += 16;
        }
        self.a = read(8, &input_lb[input_lb.len() - 16..]);
        self.b = read(8, &input_lb[input_lb.len() - 8..]);
    }

    fn final2(&mut self) -> u64 {
        self.a ^= SECRET[1];
        self.b ^= self.state[0];
        mum(&mut self.a, &mut self.b);
        mix(
            self.a ^ SECRET[0] ^ (self.total_len as u64),
            self.b ^ SECRET[1],
        )
    }
}

/// `Bun.hash(input)` — wyhash with seed 0.
pub fn bun_hash(input: &[u8]) -> u64 {
    hash_with_seed(0, input)
}

pub fn hash_with_seed(seed: u64, input: &[u8]) -> u64 {
    let mut state = State::new(seed);
    if input.len() <= 16 {
        state.small_key(input);
    } else {
        let mut index = 0usize;
        if input.len() >= 48 {
            while index + 48 < input.len() {
                state.round(&input[index..index + 48]);
                index += 48;
            }
            state.final0();
        }
        state.final1(input, index);
    }
    state.total_len = input.len();
    state.final2()
}

/// `BigInt#toString(36)` for a non-negative 64-bit value.
pub fn base36(mut value: u64) -> String {
    if value == 0 {
        return "0".to_string();
    }
    const DIGITS: &[u8; 36] = b"0123456789abcdefghijklmnopqrstuvwxyz";
    let mut out = Vec::new();
    while value > 0 {
        out.push(DIGITS[(value % 36) as usize]);
        value /= 36;
    }
    out.reverse();
    String::from_utf8(out).expect("base-36 digits are ASCII")
}

#[cfg(test)]
