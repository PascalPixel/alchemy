//--------------------------------------------------------------------------
// adjust_palette_bank.c
// メニュー：BG パレットの明るさを変えた写しを作る
//--------------------------------------------------------------------------

#include "types.h"

//--------------------------------------------------------------------------
// BG パレット 15・5・7 の 16 色の RGB に d を足し（0〜31 に収める）、
// それぞれ 1 つ前のパレット 14・4・6 に書く。7 は d でなく -12 を足す
//--------------------------------------------------------------------------
void Graphics_AdjustPaletteBank(s32 d)
{
    s32 n;
    s32 bank;
    s32 col;
    s32 mask;
    s32 idx;

    bank = 15;
    n = 0;
    mask = 31;
    do
    {
        for (col = 0; col <= 15; col++)
        {
            u32 color;
            s32 b;
            s32 g;
            s32 r;
            s32 v;

            idx = bank * 16 + col;
            color = ((u16 *)0x05000000)[idx];
            b = (color >> 10) & mask;
            g = (color >> 5) & mask;
            r = color & mask;
            b += d;
            g += d;
            r += d;
            if (b > 31)
                b = 31;
            if (g > 31)
                g = 31;
            if (r > 31)
                r = 31;
            if (b < 0)
                b = 0;
            if (g < 0)
                g = 0;
            if (r < 0)
                r = 0;
            v = b << 10;
            v |= g << 5;
            v |= r;
            ((s16 *)0x04FFFFE0)[idx] = v; // 16 色前（1 つ前のパレット）
        }
        if (n == 0)
        {
            bank = 5;
        }
        else
        {
            bank = 7;
            d = -12;
        }
        n++;
    } while (n <= 2);
}
