/// A scene's header: its scene number marked SCENE_ITEMS_HEADER, and a flag
/// (-1 for none) whose being set passes these rows over for a later header of
/// the same scene (SceneItem_GetRows). C cannot place a scene's symbol in a
/// halfword, so each header names its scene in a comment.
#define SCENE_ITEMS(scene, flag) (SCENE_ITEMS_HEADER | (scene)), (flag)

/// A treasure spot: what it is (an enum ContainerKind; for something hidden in
/// a jar, barrel, grave or wooden box, that thing's enum ExamineTarget, an
/// unseen spot Reveal makes sparkle), the scene point it stands on, the flag
/// set once it is taken (-1 for none) and what it holds: an item,
/// SCENE_ITEM_COINS, SCENE_ITEM_MIMIC, a summon tablet's summon (its flag
/// FLAG_SUMMON_TABLET), or nothing for a Psynergy Stone, whose area flag
/// brings it back once the party has left the area.
#define SCENE_ITEM(kind, point, flag, contents)                                \
  (kind), (point), (flag), (contents)

/// What a spot holds when it holds coins rather than an item: their number,
/// marked CONTAINER_COINS.
#define SCENE_ITEM_COINS(coins) (CONTAINER_COINS + (coins))

/// What a Mimic's spot holds: which of the nine Mimics jumps out of the chest,
/// counted from the Kandorean Temple's.
#define SCENE_ITEM_MIMIC(mimic) ((mimic) - ENEMY_MIMIC_KANDOREAN_TEMPLE)

