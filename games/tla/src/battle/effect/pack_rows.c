//--------------------------------------------------------------------------
// pack_rows.c
// タイル：横 2 バイトを 1 バイトに詰める
//--------------------------------------------------------------------------

#include "types.h"
#include "scene.h"

//--------------------------------------------------------------------------
// 1 行 40 バイトを 288 行、横に 2 バイトずつ 1 バイトに詰めて写す
// （あとの奇数列のバイトが残る）
// stride : src の 1 行のバイト数（dst はその半分）
//--------------------------------------------------------------------------
void Graphics_PackTileRows(u8 *src, u8 *dst, s32 stride)
{
    s32 y = 0;
    s32 h = 288;
    s32 offset = 0;

    do
    {
        s32 x;

        for (x = 0; x != 40; x++)
        {
            dst[offset / 2 + x / 2] = src[offset + x];
        }
        offset += stride;
        y++;
    } while (y != h);
}
