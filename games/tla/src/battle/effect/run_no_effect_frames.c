//--------------------------------------------------------------------------
// run_no_effect_frames.c
// バトル演出：空の演出の繰り返し
//--------------------------------------------------------------------------

#include "types.h"
#include "battle.h"

//--------------------------------------------------------------------------
// 何もしない BattleFx_RunNoEffect を cnt 回呼ぶ（フレーム待ちはしない）
// cnt : 呼ぶ回数
//--------------------------------------------------------------------------
void BattleFx_RunNoEffectFrames(s32 cnt) {
  s32 n;

  n = 0;
  if (cnt != 0) {
    do {
      n += 1;
      BattleFx_RunNoEffect();
    } while (n != cnt);
  }
}
