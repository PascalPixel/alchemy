{
	return SceneExits;
}

const ACTOR_PLACE *scGetActorPlacements(void)
{
	if(IN_ISLET_ROOMS())
		return ChampaRoomsIsletActorPlacements;
	return ChampaRoomsActorPlacements;
}

/* Champa's shops, as mnShopRun numbers them. */
enum { SHOP_CHAMPA = 25 };

/* Champa's inn, as mnInnCheckIn numbers the inns. */
enum { CHAMPA_INN = 10 };

/* Talking to the artifact merchant across his counter opens his shop. */
void scChampaRoomsTalkToArtifactMerchant(Sint32 actorId)
{
	mnShopRun(SHOP_CHAMPA, actorId);
}

/* Talking to the innkeeper across his counter opens the inn. */
void scChampaRoomsTalkToInnkeeper(Sint32 actorId)
{
	mnInnCheckIn(CHAMPA_INN, actorId);
}

const CUE *scGetCues(void)
{
	if(IN_ISLET_ROOMS())
		return ChampaRoomsIsletCues;
	if(syGameFlagGet(FLAG_BRIGGS_SAILED_FROM_ALHAFRA))
		return ChampaRoomsCuesOnceBriggsSailed;
	return ChampaRoomsCues;
}

Sint32 scInit(void)
{
	Sint32 *effect = &FieldStateWork->transition;
#if !REVISED_ENTRANCE_TRANSITIONS
	Sint32 value = SCENE_TRANSITION(TRANSITION_WINDOW, WINDOW_TRANSITION_SHAPE);
#else
	Sint32 value =
		SCENE_TRANSITION(TRANSITION_WINDOW, WINDOW_TRANSITION_LEADER);
#endif

	*effect = value;
	if(IN_ISLET_ROOMS())
		scFadeInAndClearFlag();
	return 0;
}

Sint32 scPrepareMap(void)
{
	return 0;
}

