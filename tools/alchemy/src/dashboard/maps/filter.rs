//! Screen colour filters for the live map viewer.
//!
//! Each filter turns the 32,768 GBA colours into the sRGB colour the measured
//! handheld screen shows. The measurements are Pokefan531's, published by the
//! Handheld Color Space Project
//! (https://github.com/Brankale/Handheld-Color-Space-Project, commit 3772b166).
//! The model is ordinary display colorimetry: black-corrected primaries give
//! the screen's RGB-to-XYZ matrix, and the greyscale ramp split through that
//! matrix gives one tone curve per channel. Output keeps the screen's own white
//! (no chromatic adaptation), without black-level glare, scaled down only as
//! far as that white needs to fit in sRGB. Reflective screens were measured
//! under D50 and are shown as if lit by D65 daylight.

type Xyz = [f64; 3];
type Matrix = [[f64; 3]; 3];

pub(super) struct Profile {
    pub id: &'static str,
    pub label: &'static str,
    reflective: bool,
    readings: &'static [Reading],
}

struct Reading {
    ramp: [Xyz; 32],
    white: Xyz,
    black: Xyz,
    red: Xyz,
    green: Xyz,
    blue: Xyz,
}

