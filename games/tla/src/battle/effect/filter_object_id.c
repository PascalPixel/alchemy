//--------------------------------------------------------------------------
// filter_object_id.c
// バトル演出：演出の対象オブジェクトのしぼりこみ
//--------------------------------------------------------------------------

#include "types.h"

s32 BattleFx_GetFlags();

//--------------------------------------------------------------------------
// 今の演出定義の flags が 0xff なら、対象なし (-1) を返す
// id : 対象オブジェクト番号
//--------------------------------------------------------------------------
s32 BattleFx_FilterObjectIdByFlags(s32 id)
{
    if (BattleFx_GetFlags() == 0xff)
        return -1;
    return id;
}
