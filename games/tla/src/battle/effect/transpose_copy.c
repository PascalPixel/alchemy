//--------------------------------------------------------------------------
// transpose_copy.c
// タイル：バイトの絵を右に 90 度回して写す
//--------------------------------------------------------------------------

#include "types.h"

//--------------------------------------------------------------------------
// 幅 w・高さ h の src を、幅 h・高さ w の dst に右へ 90 度回して写す
// （src のいちばん上の行が dst のいちばん右の列になる）
//--------------------------------------------------------------------------
void Graphics_TransposeCopy(const u8 *src, u8 *dst, s32 w, s32 h)
{
    s32       y;
    s32       x;
    s32       col;
    s32       offset;
    u8       *d;
    const u8 *s;

    y = 0;
    if (h != 0)
    {
        offset = 0;
        col = h;
        do
        {
            x = 0;
            if (w != 0)
            {
                d = (u8 *)(col + (u32)dst - 1);
                s = (const u8 *)(offset + (u32)src);
                do
                {
                    x++;
                    *d = *s;
                    s++;
                    d += h;
                } while (x != w);
            }
            y++;
            offset += w;
            col--;
        } while (y != h);
    }
}
