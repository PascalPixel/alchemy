const BRADFORD_D50_TO_D65: Matrix = [
    [0.9555766, -0.0230393, 0.0631636],
    [-0.0282895, 1.0099416, 0.0210077],
    [0.0122982, -0.0204830, 1.3299098],
];
const XYZ_TO_LINEAR_SRGB: Matrix = [
    [3.2404542, -1.5371385, -0.4985314],
    [-0.9692660, 1.8760108, 0.0415560],
    [0.0556434, -0.2040259, 1.0572252],
];

fn sub(a: Xyz, b: Xyz) -> Xyz {
    [a[0] - b[0], a[1] - b[1], a[2] - b[2]]
}
fn apply(m: &Matrix, v: Xyz) -> Xyz {
    m.map(|row| row[0] * v[0] + row[1] * v[1] + row[2] * v[2])
}
fn invert(m: &Matrix) -> Matrix {
    let [[a, b, c], [d, e, f], [g, h, i]] = *m;
    let det = a * (e * i - f * h) - b * (d * i - f * g) + c * (d * h - e * g);
    [
        [e * i - f * h, c * h - b * i, b * f - c * e],
        [f * g - d * i, a * i - c * g, c * d - a * f],
        [d * h - e * g, b * g - a * h, a * e - b * d],
    ]
    .map(|row| row.map(|v| v / det))
}
fn encode(linear: f64) -> u8 {
    let v = linear.clamp(0.0, 1.0);
    let v = if v <= 0.0031308 {
        12.92 * v
    } else {
        1.055 * v.powf(1.0 / 2.4) - 0.055
    };
    (v * 255.0).round() as u8
}

/// The profile's readings averaged as light, which the project uses to combine
/// the two meter orientations of the reflective screens.
fn average(readings: &[Reading]) -> Reading {
    let n = readings.len() as f64;
    let mean = |pick: &dyn Fn(&Reading) -> Xyz| {
        let mut sum = [0.0; 3];
        for reading in readings {
            let v = pick(reading);
            for c in 0..3 {
                sum[c] += v[c] / n;
            }
        }
        sum
    };
    Reading {
        ramp: std::array::from_fn(|level| mean(&|r| r.ramp[level])),
        white: mean(&|r| r.white),
        black: mean(&|r| r.black),
        red: mean(&|r| r.red),
        green: mean(&|r| r.green),
        blue: mean(&|r| r.blue),
    }
}

/// The screen's white-normalised RGB-to-XYZ matrix and linear light per
/// channel at each of the 32 levels.
fn model(readings: &[Reading]) -> (Matrix, [[f64; 32]; 3]) {
    let reading = average(readings);
    let primaries = [reading.red, reading.green, reading.blue].map(|p| sub(p, reading.black));
    let mut screen: Matrix = std::array::from_fn(|row| primaries.map(|p| p[row]));
    // Scale each primary so full white is exactly the measured white.
    let gains = apply(&invert(&screen), sub(reading.white, reading.black));
    let white_y = reading.white[1] - reading.black[1];
    for row in &mut screen {
        for c in 0..3 {
            row[c] *= gains[c] / white_y;
        }
    }
    let to_channels = invert(&screen);
    let top = apply(&to_channels, sub(reading.ramp[31], reading.ramp[0]));
    let mut curves = [[0.0; 32]; 3];
    for level in 1..32 {
        let v = apply(&to_channels, sub(reading.ramp[level], reading.ramp[0]));
        for c in 0..3 {
            // Meter noise near black can dip below the previous step.
            curves[c][level] = (v[c] / top[c]).clamp(curves[c][level - 1], 1.0);
        }
    }
    curves.iter_mut().for_each(|curve| curve[31] = 1.0);
    (screen, curves)
}

/// RGB bytes for every GBA colour, indexed by its 15-bit BGR555 value.
pub(super) fn table(profile: &Profile) -> Vec<u8> {
    let (screen, curves) = model(profile.readings);
    let to_srgb = |channels: Xyz| {
        let xyz = apply(&screen, channels);
        let xyz = if profile.reflective {
            apply(&BRADFORD_D50_TO_D65, xyz)
        } else {
            xyz
        };
        apply(&XYZ_TO_LINEAR_SRGB, xyz)
    };
    let white = to_srgb([1.0; 3]);
    let peak = white.iter().copied().fold(1.0, f64::max);
    let mut bytes = Vec::with_capacity(32768 * 3);
    for color in 0..32768usize {
        let channels = [0, 5, 10].map(|shift| (color >> shift) & 31);
        let linear = to_srgb(std::array::from_fn(|c| curves[c][channels[c]]));
        bytes.extend(linear.map(|v| encode(v / peak)));
    }
    bytes
}

#[test]
fn every_profile_maps_all_colours_monotonically() {
    for profile in &PROFILES {
        let table = table(profile);
        assert_eq!(table.len(), 32768 * 3, "{}", profile.id);
        assert_eq!(&table[..3], &[0, 0, 0], "{} black", profile.id);
        let white = &table[32767 * 3..];
        assert!(
            white.iter().any(|&v| v == 255),
            "{} white {white:?}",
            profile.id
        );
        assert!(
            white.iter().all(|&v| v > 200),
            "{} white {white:?}",
            profile.id
        );
        for shift in [0, 5, 10] {
            let mut previous = 0;
            for level in 0..32usize {
                let at = (level << shift) * 3;
                let value = table[at..at + 3].iter().map(|&v| v as u32).sum::<u32>();
                assert!(
                    value >= previous,
                    "{} channel {shift} level {level}",
                    profile.id
                );
                previous = value;
            }
        }
    }
}

#[test]
fn derived_ags_101_curve_tracks_the_published_shader_gamma() {
    // The project's AGS-101 shader, from the same console measured in 2023,
    // gives red gamma 2.428, 2.271 and 2.729 at levels 3, 9 and 20.
    let (_, curves) = model(&AGS_101);
    for (level, published) in [(3, 2.428), (9, 2.271), (20, 2.729)] {
        let gamma = curves[0][level].ln() / (level as f64 / 31.0).ln();
        assert!((gamma - published).abs() < 0.1, "level {level}: {gamma}");
    }
}

